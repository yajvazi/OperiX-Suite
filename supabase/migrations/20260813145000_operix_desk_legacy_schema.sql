-- `public.users` is deny-by-default because it contains password-hash
-- compatibility fields. RLS policies on Desk child tables use this narrowly
-- scoped security-definer predicate instead of exposing that table to clients.
create or replace function private.desk_user_matches_auth(
  p_user_id integer,
  p_company_id uuid
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.users desk_user
    where desk_user.id = p_user_id
      and desk_user.supabase_user_id = (select auth.uid())::text
      and desk_user.company_id = p_company_id::text
  );
$$;

revoke all on function private.desk_user_matches_auth(integer, uuid) from public;
grant execute on function private.desk_user_matches_auth(integer, uuid) to authenticated, service_role;

alter table public.desk_device_tokens enable row level security;
drop policy if exists operix_desk_device_tokens_manage on public.desk_device_tokens;
create policy operix_desk_device_tokens_manage on public.desk_device_tokens
for all to authenticated
using (
  company_id is not null
  and public.can_access_company(company_id::uuid)
  and private.desk_user_matches_auth(user_id, company_id::uuid)
)
with check (
  company_id is not null
  and public.can_access_company(company_id::uuid)
  and private.desk_user_matches_auth(user_id, company_id::uuid)
);

