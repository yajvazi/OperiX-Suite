-- OperiX Desk legacy tables in the shared Supabase/Postgres database.
--
-- The original Desk copy kept these migrations under its app directory, so a
-- fresh OperiX database would otherwise reach the shared-workspace migration
-- without the legacy tables it extends. This migration is idempotent for
-- installations that already applied the app-local Desk migrations.

do $$
begin
  if not exists (select 1 from pg_type where typnamespace = 'public'::regnamespace and typname = 'userrole') then
    create type public.userrole as enum ('employee', 'team_leader', 'manager', 'admin');
  end if;
  if not exists (select 1 from pg_type where typnamespace = 'public'::regnamespace and typname = 'resourcetype') then
    create type public.resourcetype as enum ('desk', 'room', 'amenity');
  end if;
  if not exists (select 1 from pg_type where typnamespace = 'public'::regnamespace and typname = 'reservationstatus') then
    create type public.reservationstatus as enum ('active', 'cancelled', 'resource_removed');
  end if;
end
$$;

alter type public.resourcetype add value if not exists 'amenity';

