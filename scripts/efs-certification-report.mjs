import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(process.env.EFS_EVIDENCE_DIR || join(root, "artifacts", "efs-certification-report"));

const sourceFiles = [
  "docs/compliance/kosovo-efs-requirements-2026.md",
  "docs/live/OPERIX-EFS-PREIMPLEMENTATION-AUDIT.md",
  "docs/live/OPERIX-KOSOVO-EFS-CERTIFICATION-READINESS.md",
  "docs/efs/README.md",
  "docs/efs/ARCHITECTURE.md",
  "docs/efs/FISCAL-FLOW.md",
  "docs/efs/TAK-INTEGRATION.md",
  "docs/efs/RECEIPT-SPECIFICATION.md",
  "docs/efs/CRYPTOGRAPHY.md",
  "docs/efs/KEY-MANAGEMENT.md",
  "docs/efs/CERTIFICATES.md",
  "docs/efs/ERROR-HANDLING.md",
  "docs/efs/OFFLINE-RECOVERY.md",
  "docs/efs/SECURITY.md",
  "docs/efs/OPERATIONS.md",
  "docs/efs/CHANGE-CONTROL.md",
  "docs/efs/CERTIFICATION.md",
  "docs/efs/certification-package",
  "packages/fiscalization/src/index.ts",
  "packages/fiscalization/src/index.test.ts",
  "supabase/migrations/20260812154150_kosovo_efs_certification_readiness_20260812.sql",
  "supabase/migrations/20260812161000_efs_tenant_and_receipt_access_hardening.sql",
  "supabase/tests/kosovo_efs_readiness.sql",
];

function git(args) {
  try {
    return execFileSync("git", args, { cwd: root, encoding: "utf8" }).trim();
  } catch {
    return "unavailable";
  }
}

function copySafe(source) {
  const absoluteSource = join(root, source);
  if (!existsSync(absoluteSource)) return false;
  const destination = join(output, source);
  cpSync(absoluteSource, destination, { recursive: true });
  return true;
}

mkdirSync(output, { recursive: true });
const copied = sourceFiles.filter(copySafe);
const manifest = {
  product: "OperiX Invoice",
  generatedAt: new Date().toISOString(),
  gitCommit: git(["rev-parse", "HEAD"]),
  workingTree: git(["status", "--short"]) ? "dirty" : "clean",
  fiscalModule: "packages/fiscalization",
  certificationStatus: "EFS NOT CERTIFIED — DO NOT USE OPERIX AS A CERTIFIED FISCAL RECEIPT SYSTEM",
  productionFiscalizationEnabled: false,
  privateKeysIncluded: false,
  secretsIncluded: false,
  copiedFiles: copied,
  omittedFiles: sourceFiles.filter((source) => !copied.includes(source)),
};

const hashes = Object.fromEntries(copied.map((source) => {
  const file = join(output, source);
  if (!existsSync(file) || !statSync(file).isFile()) return [source, "directory"];
  return [source, createHash("sha256").update(readFileSync(file)).digest("hex")];
}));

writeFileSync(join(output, "software-manifest.json"), JSON.stringify({ ...manifest, hashes }, null, 2));
writeFileSync(join(output, "README.md"), `# OperiX EFS certification evidence\n\nGenerated by \`pnpm efs:certification-report\`.\n\nThis bundle contains source references, tests, schemas, and documentation only. It intentionally contains no private keys, credentials, passwords, or production TAK responses.\n\nProduction fiscalization remains disabled and this bundle is not a TAK certificate.\n`);
console.log(`EFS certification evidence written to ${relative(root, output) || output}`);
