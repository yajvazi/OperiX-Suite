export type TranslationKey = keyof typeof translations.en;

export function t(key: TranslationKey, locale: string = 'en'): string {
    const lang = translations[locale as keyof typeof translations] || translations.en;
    return lang[key] || key;
}

/**
 * Keeps the detailed server error for English users while preventing raw,
 * usually English, backend/transport messages from leaking into the
 * Albanian UI. Known transport states still get a useful localized label.
 */
export function getLocalizedErrorMessage(
    error: unknown,
    locale: string = activeLocale,
    fallback: TranslationKey = 'somethingWentWrong',
): string {
    const message = error instanceof Error
        ? error.message
        : typeof error === 'string'
            ? error
            : error && typeof error === 'object' && 'message' in error
                ? String((error as { message?: unknown }).message || '')
                : '';
    if (!message) return t(fallback, locale);
    const code = error && typeof error === 'object' && 'code' in error
        ? String((error as { code?: unknown }).code || '')
        : '';
    if (code === '42501') return t('permissionDenied', locale);
    if (normalizeLocale(locale) === 'en') return message;

    const normalized = message.toLowerCase();
    if (
        normalized.includes('network')
        || normalized.includes('fetch')
        || normalized.includes('timeout')
        || normalized.includes('offline')
        || normalized.includes('name resolution')
        || normalized.includes('service unavailable')
        || normalized.includes('edge function')
        || normalized.includes('returned an invalid response')
    ) {
        return t('connectionFailed', locale);
    }
    if (
        normalized.includes('posted or issued')
        || normalized.includes('cannot be deleted')
        || normalized.includes('correction or reversal')
    ) {
        return t('immutableDocumentMessage', locale);
    }
    if (normalized.includes('cancel')) return t('cancelled', locale);
    if (normalized.includes('not found') || normalized.includes('does not exist')) return t('notFound', locale);
    return t(fallback, locale);
}
