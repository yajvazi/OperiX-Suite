// Localization helpers and formatters

export const currencies: Record<string, { symbol: string; name: string; locale: string }> = {
    USD: { symbol: '$', name: 'US Dollar', locale: 'en-US' },
    EUR: { symbol: '€', name: 'Euro', locale: 'de-DE' },
    GBP: { symbol: '£', name: 'British Pound', locale: 'en-GB' },
    JPY: { symbol: '¥', name: 'Japanese Yen', locale: 'ja-JP' },
    CAD: { symbol: 'C$', name: 'Canadian Dollar', locale: 'en-CA' },
    AUD: { symbol: 'A$', name: 'Australian Dollar', locale: 'en-AU' },
    CHF: { symbol: 'Fr', name: 'Swiss Franc', locale: 'de-CH' },
    CNY: { symbol: '¥', name: 'Chinese Yuan', locale: 'zh-CN' },
    INR: { symbol: '₹', name: 'Indian Rupee', locale: 'en-IN' },
};

export type AppLocale = 'en' | 'sq';

let activeLocale: AppLocale = 'en';

export function normalizeLocale(locale?: string | null): AppLocale {
    return locale?.toLowerCase().startsWith('sq') ? 'sq' : 'en';
}

export function setAppLocale(locale: string): void {
    activeLocale = normalizeLocale(locale);
}

export function getAppLocale(): AppLocale {
    return activeLocale;
}

function intlLocale(locale: string): string {
    return normalizeLocale(locale) === 'sq' ? 'sq-XK' : 'en-US';
}

export function formatCurrency(amount: number, currencyCode: string = 'EUR', locale: string = activeLocale): string {
    const code = currencies[currencyCode] ? currencyCode : 'EUR';
    return new Intl.NumberFormat(intlLocale(locale), {
        style: 'currency',
        currency: code,
        currencyDisplay: 'symbol',
        minimumFractionDigits: 2,
        maximumFractionDigits: 2,
    }).format(Number.isFinite(amount) ? amount : 0);
}

export function formatDate(dateString: string, locale: string = activeLocale): string {
    return new Date(dateString).toLocaleDateString(intlLocale(locale), {
        year: 'numeric',
        month: 'short',
        day: 'numeric',
    });
}

export function formatDateLong(dateString: string, locale: string = activeLocale): string {
    return new Date(dateString).toLocaleDateString(intlLocale(locale), {
        year: 'numeric',
        month: 'long',
        day: 'numeric',
    });
}

