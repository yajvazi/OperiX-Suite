const translateText = (text: string, extra: Record<string, string> = {}) => {
  const trimmed = text.trim();
  if (!trimmed) return text;
  if (extra[trimmed] || EXACT[trimmed]) return text.replace(trimmed, extra[trimmed] || EXACT[trimmed]);
  let result = text;
  for (const [sq, en] of PREFIXES) if (result.includes(sq)) result = result.replace(sq, en);
  return result;
};

/** English version of a report built from the Albanian templates. Tags and styles are untouched; `alt` texts are translated too. */
export function translateReportHtml(html: string, language: ReportLanguage = "sq", extra: Record<string, string> = {}) {
  if (language !== "en") return html;
  let inStyle = false;
  return html
    .split(/(<[^>]+>)/)
    .map((part) => {
      if (part.startsWith("<")) {
        if (/^<style[\s>]/i.test(part)) inStyle = true;
        else if (/^<\/style>/i.test(part)) inStyle = false;
        return part.replace(/alt="([^"]*)"/g, (_match, alt: string) => `alt="${EXACT[alt] || alt}"`).replace('<html lang="sq"', '<html lang="en"');
      }
      return inStyle ? part : translateText(part, extra);
    })
    .join("");
}
